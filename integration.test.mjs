test('the shared portal source is immutable and generated bytes match reviewed integrity pins',async()=>{
  const manifest=JSON.parse(await read('portal-source.json'));
  assert.match(manifest.commit,/^[0-9a-f]{40}$/);
  for(const f of manifest.files){
    const data=await readFile(new URL(f.destination,root));
    if(f.gitBlobSha){const blob=createHash('sha1').update(`blob ${data.length}\0`).update(data).digest('hex');assert.equal(blob,f.gitBlobSha,f.source);}
    else assert.equal(createHash('sha256').update(data).digest('hex'),f.sha256,f.source);
  }
});
