import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root=new URL('./',import.meta.url),read=p=>readFile(new URL(p,root),'utf8');
test('www routes preserve legacy campaigns and the old lead endpoint',async()=>{
  const config=JSON.parse(await read('vercel.json'));
  assert.ok(config.rewrites.some(r=>r.source==='/varanda-botanic' && r.destination==='/varanda-botanic/index.html'));
  assert.ok(config.rewrites.some(r=>r.source==='/varanda-botanic/' && r.destination==='/varanda-botanic/index.html'));
  assert.ok(!config.rewrites.some(r=>r.source==='/api/lead'));
  assert.ok(config.rewrites.some(r=>r.source==='/api/portal/lead' && r.destination==='https://app.yincorp.com.br/api/lead'));
  assert.equal(config.redirects[0].permanent,false);
});
test('the shared portal source is immutable and generated bytes match the reviewed hashes',async()=>{
  const manifest=JSON.parse(await read('portal-source.json'));
  assert.match(manifest.commit,/^[0-9a-f]{40}$/);
  for(const f of manifest.files){const data=await readFile(new URL(f.destination,root));assert.equal(createHash('sha256').update(data).digest('hex'),f.sha256,f.source);}
});
test('canonical is www; runtime exposes no privileged Supabase credential',async()=>{
  const entry=await read('api/portal.js'),publicConfig=await read('.portal-shared/public-config.js');
  assert.match(entry,/canonicalOrigin:'https:\/\/www.yincorp.com.br'/);assert.match(publicConfig,/sb_publishable_/);assert.doesNotMatch(publicConfig,/sb_secret_|service_role/);
  const robots=await read('robots.txt');assert.match(robots,/www.yincorp.com.br\/sitemap.xml/);assert.match(robots,/www.yincorp.com.br\/sitemap-portal.xml/);
});
